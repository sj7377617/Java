package Operators;

public class RelationalOperator {
    public static void main(String[] args) {
        
        int a = 10;
        int b = 20;
        int c = 30;

        System.out.println("Equal to:"+(a==b));
        System.out.println("Not Equal to:"+ (a!=b));
        System.out.println("Greater than:"+ (a>b));
        System.out.println("Less than:"+ (b<c));

    }
}
